import psycopg2
import pytest
from faker import Faker

table_name = 'users_test'


@pytest.fixture()
def db_connection():
    connection = psycopg2.connect(
        dbname="aqa_docker",
        user="qa",
        password="123QWE",
        host="db",
        port="5432"
    )

    cursor = connection.cursor()

    create_query = f'''
        create table if not exists public.{table_name} (
        id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
        "name" varchar NULL,
        description varchar NULL,
        phone varchar NULL,
        CONSTRAINT users_test_pk PRIMARY KEY (id)
    	); '''
    cursor.execute(create_query)
    connection.commit()

    yield connection, cursor

    cursor.close()
    connection.close()


def test_connect_to_db_is_successful(db_connection):
    connection, _ = db_connection
    assert connection is not None


def test_create_user(db_connection):
    connection, cursor = db_connection
    faker = Faker('en_US')
    target_user_name = faker.name()

    insert_query = f'''
    INSERT into {table_name} (name, description, phone)
    VALUES ('{target_user_name}', '{faker.word()}', '{faker.phone_number()}')
    RETURNING id;
    '''

    cursor.execute(insert_query)
    target_user_id = cursor.fetchone()[0]
    connection.commit()

    cursor.execute(f"SELECT name FROM {table_name} where id = {target_user_id}")
    result = cursor.fetchone()
    assert result[0] == target_user_name, f"Expected user name: {target_user_name}, but got: {result[0]}"


def test_update_last_user(db_connection):
    connection, cursor = db_connection
    cursor.execute(f"SELECT id FROM {table_name} ORDER BY ID DESC")
    target_user_id = cursor.fetchone()[0]

    connection, cursor = db_connection
    update_query = f'''
    UPDATE users_test
    set description = 'UPDATED'
    where id = {target_user_id}
    '''
    cursor.execute(update_query)
    connection.commit()

    cursor.execute(f"SELECT description FROM {table_name} where id = {target_user_id}")
    result = cursor.fetchone()
    assert result[0] == 'UPDATED', f"Expected description is 'UPDATED', but got: {result[0]}"


def test_delete_last_user(db_connection):
    connection, cursor = db_connection
    cursor.execute(f"SELECT id FROM {table_name} ORDER BY ID DESC")
    target_user_id = cursor.fetchone()[0]

    delete_query = f'''
    DELETE
    FROM users_test
    where id = {target_user_id}
    RETURNING id
    '''
    cursor.execute(delete_query)
    resulting_user_id = cursor.fetchone()[0]
    connection.commit()

    assert resulting_user_id == target_user_id, f"Expected deleted user id to be {target_user_id}, but got {resulting_user_id}"
